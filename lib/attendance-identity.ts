export function normalizeAttendanceEmployeeName(name: string) {
  return name
    .trim()
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[.,]/g, ' ')
    .replace(/\s+/g, ' ');
}

export function canonicalAttendanceEmployeeName(name: string) {
  const normalized = normalizeAttendanceEmployeeName(name);
  return employeeAliases[normalized] ?? name.trim().replace(/\s+/g, ' ');
}

export function attendanceEmployeeKey(name: string) {
  return normalizeAttendanceEmployeeName(canonicalAttendanceEmployeeName(name));
}
