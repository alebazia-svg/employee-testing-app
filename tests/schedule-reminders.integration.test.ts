import test from 'node:test';
import assert from 'node:assert/strict';
import { PrismaClient } from '@prisma/client';
import { activeScheduleNotices, reconcileScheduleNearQuestions } from '../lib/work-schedule-notifications';
import { persistEmployeeScheduleChange } from '../lib/work-schedule-persistence';
import { reconcileScheduleCoverageQuestion, loadScheduleCoverageQuestions, queueScheduleFillQuestions } from '../lib/schedule-coverage-reconciliation';
import { SCHEDULE_NEAR_KIND } from '../lib/schedule-near-reminder';

test('isolated DB: only today/tomorrow, one daily source, no repeats, legacy retirement and next-day advance', {skip:process.env.SCHEDULE_REMINDER_TEST!=='1'},async()=>{
 const url=new URL(process.env.DATABASE_URL!);assert.equal(url.hostname,'127.0.0.1');assert.equal(url.port,'55471');assert.equal(url.pathname,'/schedule_preview_20261026');
 const db=new PrismaClient(),date='2099-10-26',now=new Date('2099-10-26T05:30Z'),prefix=`schedule-proof-${Date.now()}`;
 const ids:number[]=[];
 try {
  const admin=await db.user.create({data:{login:prefix+'admin',name:'Учебный ADMIN',passwordHash:'disabled',role:'ADMIN'}});ids.push(admin.id);
  const liana=await db.user.create({data:{login:prefix+'a',name:'Пример Лиана',passwordHash:'disabled',role:'EMPLOYEE',department:'wholesale'}});ids.push(liana.id);
  const zalina=await db.user.create({data:{login:prefix+'b',name:'Пример Залина',passwordHash:'disabled',role:'EMPLOYEE',department:'wholesale'}});ids.push(zalina.id);
  const old=await db.workdayNotification.create({data:{userId:zalina.id,kind:'schedule_week_fill_request',fingerprint:`schedule-week:wholesale:${date}:${zalina.id}`,title:'Weekly',body:'',scheduledAt:now,status:'sent',sentAt:now,pushStatus:'delivered',pushDeliveredAt:now}});
  assert.equal((await activeScheduleNotices(db,[old],date)).size,0,'old weekly obligation is hidden immediately');
  await queueScheduleFillQuestions(db,new Date('2099-10-26T05:29Z'));
  const fingerprint=`schedule-near:wholesale:${date}:${zalina.id}`;
  assert.equal(await db.workdayNotification.count({where:{fingerprint}}),0,'new push cycle begins at 08:30 Moscow');
  await reconcileScheduleNearQuestions(db,'wholesale',now);
  const notice=await db.workdayNotification.findUniqueOrThrow({where:{fingerprint}});
  assert.equal((await db.workdayNotification.findUniqueOrThrow({where:{id:old.id}})).status,'resolved');
  assert.equal(notice.pushStatus,'cancelled','accepted legacy push today is not replayed');
  assert.equal(notice.pushDeliveredAt,null,'migration does not invent a provider-delivery receipt');
  assert.equal(notice.kind,SCHEDULE_NEAR_KIND);
  await db.workdayNotification.update({where:{id:notice.id},data:{status:'sent',sentAt:now,readAt:now,pushStatus:'delivered',pushDeliveredAt:now}});
  assert.equal((await activeScheduleNotices(db,[notice],date)).size,1,'reading is not completion');
  for(let i=0;i<2;i++)await reconcileScheduleNearQuestions(db,'wholesale',now);
  assert.equal(await db.workdayNotification.count({where:{fingerprint}}),1);
  await db.$transaction(tx=>persistEmployeeScheduleChange(tx,{user:zalina,date,status:'working',previousStatus:null,departmentEntries:[],source:'employee'}));
  await reconcileScheduleNearQuestions(db,'wholesale',now);
  assert.match((await db.workdayNotification.findUniqueOrThrow({where:{fingerprint}})).body,/^Завтра не заполнен\./);
  await db.workScheduleEntry.create({data:{userId:zalina.id,date:'2099-10-27',department:'wholesale',status:'off'}});
  assert.equal((await activeScheduleNotices(db,[notice],date)).size,0,'both near dates filled; the empty rest of week/month is irrelevant');
  await reconcileScheduleNearQuestions(db,'wholesale',now);
  assert.equal((await db.workdayNotification.findUniqueOrThrow({where:{fingerprint}})).status,'resolved');
  await db.workScheduleEntry.delete({where:{userId_date:{userId:zalina.id,date:'2099-10-27'}}});
  await reconcileScheduleNearQuestions(db,'wholesale',now);
  const reopened=await db.workdayNotification.findUniqueOrThrow({where:{fingerprint}});
  assert.equal(reopened.status,'sent');assert.equal(reopened.pushStatus,'cancelled');assert.equal(+reopened.sentAt!,+now);
  await db.employeeVacation.create({data:{userId:zalina.id,department:'wholesale',dateFrom:'2099-10-27',dateTo:'2099-10-27',status:'active',createdById:admin.id,updatedById:admin.id}});
  assert.equal((await activeScheduleNotices(db,[reopened],date)).size,0);
  const nextDay=new Date('2099-10-27T05:30Z');
  await reconcileScheduleNearQuestions(db,'wholesale',nextDay);
  const nextKey=`schedule-near:wholesale:2099-10-27:${zalina.id}`;
  const next=await db.workdayNotification.findUniqueOrThrow({where:{fingerprint:nextKey}});
  assert.equal(next.status,'pending','new day can remind about the following day, without a weekly obligation');
  assert.match(next.body,/^Завтра не заполнен\./);
  assert.equal((await activeScheduleNotices(db,[reopened],'2099-10-27')).size,0);
  await reconcileScheduleNearQuestions(db,'wholesale',nextDay);
  assert.equal(await db.workdayNotification.count({where:{fingerprint:nextKey}}),1);
  await db.workScheduleEntry.create({data:{userId:zalina.id,date:'2099-10-28',department:'wholesale',status:'off'}});
  assert.equal((await activeScheduleNotices(db,[next],'2099-10-27')).size,0,'29th is outside the reminder horizon');
  await db.workScheduleEntry.create({data:{userId:liana.id,date,department:'wholesale',status:'working'}});
  await reconcileScheduleCoverageQuestion(db,'wholesale',date,now);
  assert.equal((await loadScheduleCoverageQuestions(db,[`wholesale:${date}`],now)).get(`wholesale:${date}`)?.active,false);
  await db.$transaction(tx=>persistEmployeeScheduleChange(tx,{user:liana,date,status:'off',previousStatus:'working',departmentEntries:[{userId:liana.id,status:'working'},{userId:zalina.id,status:'working'}],source:'employee'}));
  assert.equal((await loadScheduleCoverageQuestions(db,[`wholesale:${date}`],now)).get(`wholesale:${date}`)?.active,true);
 } finally {
  await db.workdayNotification.deleteMany({where:{fingerprint:{startsWith:'schedule-near:wholesale:2099-10-2'}}});
  await db.adminInboxEvent.deleteMany({where:{eventKey:`schedule-coverage:wholesale:${date}`}});
  await db.employeeVacation.deleteMany({where:{userId:{in:ids}}});
  await db.user.deleteMany({where:{id:{in:ids}}});await db.$disconnect();
 }
});
