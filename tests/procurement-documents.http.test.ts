import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {PrismaClient} from '@prisma/client';
const base='http://127.0.0.1:3167';
if(process.env.DATABASE_URL!=='postgresql://postgres@127.0.0.1:55467/payment_documents_test')throw Error('ISOLATED_DOCUMENTS_TEST_DATABASE_REQUIRED');
const db=new PrismaClient();test.after(()=>db.$disconnect());
test('actual HTTP routes: scoped auth, purpose persistence, legacy filtering, receipt coverage, CSRF and file access',async()=>{
  const login=async(name:string)=>{
    const response=await fetch(base+'/api/auth/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({login:name,password:'documents-local-only'})});
    assert.equal(response.status,200);
    return response.headers.getSetCookie().find(c=>c.startsWith('offonika_session='))!.split(';')[0];
  };
  const admin=await login('documents-admin'),buyer=await login('documents-buyer');
  const endpoint=base+'/api/procurement/payment-plans/documents-paid/receipts';
  const marker=randomUUID();
  const form=(purpose:string,refs?:string[])=>{
    const data=new FormData();data.set('purpose',purpose);data.set('file',new Blob([`%PDF-1.7\n${marker}-${purpose}\n%%EOF`],{type:'application/pdf'}),`${purpose}-local-test.pdf`);
    if(refs)data.set('paymentRefs',JSON.stringify(refs));return data;
  };
  assert.equal((await fetch(endpoint,{method:'POST',body:form('QR')})).status,401);
  assert.equal((await fetch(endpoint,{method:'POST',headers:{cookie:buyer,origin:'https://example.invalid'},body:form('QR')})).status,403);
  const qrResponse=await fetch(endpoint,{method:'POST',headers:{cookie:buyer,origin:base},body:form('QR')});
  assert.equal(qrResponse.status,201);const qr=(await qrResponse.json()).receipt;
  const legacy=await (await fetch(endpoint,{headers:{cookie:admin}})).json();
  assert.equal(legacy.receipts.some((r:any)=>r.id===qr.id),false);
  const modern=await (await fetch(endpoint+'?documents=1',{headers:{cookie:admin}})).json();
  assert.equal(modern.receipts.some((r:any)=>r.id===qr.id&&r.purpose==='QR'),true);
  const download=await fetch(endpoint+'/'+qr.id,{headers:{cookie:admin}});assert.equal(download.status,200);
  assert.equal(download.headers.get('x-content-type-options'),'nosniff');
  const wrong=await fetch(endpoint,{method:'POST',headers:{cookie:buyer,origin:base},body:form('RECEIPT',['cash:not-this-plan'])});
  assert.equal(wrong.status,409);
  const paid=await fetch(endpoint,{method:'POST',headers:{cookie:buyer,origin:base},body:form('RECEIPT',['cash:local-rko'])});
  assert.equal(paid.status,201);const receipt=(await paid.json()).receipt;
  assert.deepEqual(receipt.paymentRefs,['cash:local-rko']);
  const patchUrl=base+`/api/procurement/payment-plans/documents-paid/documents/${receipt.id}`;
  const patch={action:'CLASSIFY',revision:0,purpose:'REQUISITES'};
  assert.equal((await fetch(patchUrl,{method:'PATCH',headers:{cookie:buyer,origin:base,'Content-Type':'application/json'},body:JSON.stringify(patch)})).status,403);
  assert.equal((await fetch(patchUrl,{method:'PATCH',headers:{cookie:admin,origin:'https://example.invalid','Content-Type':'application/json'},body:JSON.stringify(patch)})).status,403);
  const result=await fetch(patchUrl,{method:'PATCH',headers:{cookie:admin,origin:base,'Content-Type':'application/json'},body:JSON.stringify(patch)});
  assert.equal(result.status,200);assert.equal((await result.json()).receipt.purpose,'REQUISITES');
  assert.equal((await fetch(patchUrl,{method:'PATCH',headers:{cookie:admin,origin:base,'Content-Type':'application/json'},body:JSON.stringify(patch)})).status,409);
  const listed=await(await fetch(endpoint,{headers:{cookie:admin}})).json();
  assert.equal(listed.receipts.some((r:any)=>r.id===receipt.id),false);
  const restore=(refs?:string[])=>fetch(patchUrl,{method:'PATCH',headers:{cookie:admin,origin:base,'Content-Type':'application/json'},body:JSON.stringify({action:'CLASSIFY',revision:1,purpose:'RECEIPT',paymentRefs:refs})});
  assert.notEqual((await restore()).status,200,'reclassification cannot silently cover all expenses');
  assert.notEqual((await restore(['cash:another-plan'])).status,200);
  const restored=await restore(['cash:local-rko']);assert.equal(restored.status,200);
  const restoredFile=(await restored.json()).receipt;
  assert.equal(restoredFile.purpose,'RECEIPT');assert.deepEqual(restoredFile.paymentRefs,['cash:local-rko']);
  assert.ok(restoredFile.paymentSnapshots['cash:local-rko']);
  assert.equal((await fetch(endpoint+'/'+receipt.id,{headers:{cookie:admin}})).status,200,'original file stays accessible');
});

test('manual QR HTTP request: admin-only, CSRF, concurrency dedup, stale state and method guards',async()=>{
  const login=async(name:string)=>{
    const r=await fetch(base+'/api/auth/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({login:name,password:'documents-local-only'})});
    assert.equal(r.status,200);return r.headers.getSetCookie().find(c=>c.startsWith('offonika_session='))!.split(';')[0];
  };
  const admin=await login('documents-admin'),buyer=await login('documents-buyer');
  const owner=await db.user.findUniqueOrThrow({where:{login:'documents-buyer'}});
  const plan=await db.supplierPaymentPlan.create({data:{planCode:`manual-qr-test-${randomUUID()}`,managerUserId:owner.id,supplierPartner:'MANUAL QR TEST ONLY',orderRefs:[],orderNumbers:[],plannedDate:new Date('2026-10-30'),plannedAmount:100,condition:'local-only',paymentMethod:'CNY',status:'APPROVED'}});
  const endpoint=base+`/api/procurement/payment-plans/${plan.id}/qr-request`;
  const body={planVersion:plan.updatedAt.toISOString(),qrFiles:[]};
  const send=(cookie=admin,origin=base,data:any=body)=>fetch(endpoint,{method:'POST',headers:{cookie,origin,'Content-Type':'application/json'},body:JSON.stringify(data)});
  assert.equal((await send('')).status,401);
  assert.equal((await send(buyer)).status,403);
  assert.equal((await send(admin,'https://example.invalid')).status,403);
  assert.equal((await send(admin,base,{})).status,400);
  assert.equal((await send(admin,base,{...body,planVersion:'2026-01-01'})).status,409);
  const responses=await Promise.all([send(),send()]);
  assert.ok(responses.every(r=>r.status===200));
  const results=await Promise.all(responses.map(r=>r.json()));
  assert.equal(results.filter(r=>r.alreadyRequested===false).length,1);
  const rows=await db.workdayNotification.findMany({where:{fingerprint:{startsWith:`procurement-qr-check:${plan.id}:`}}});
  assert.equal(rows.length,1);assert.equal(rows[0].title,'Добавьте QR-код для оплаты');assert.equal(rows[0].status,'pending');
  assert.equal(rows[0].attemptCount,0,'test never dispatches a push');
  const changed=await db.supplierPaymentPlan.update({where:{id:plan.id},data:{paymentMethod:'CASH'}});
  assert.equal((await send(admin,base,{...body,planVersion:changed.updatedAt.toISOString()})).status,409);
  assert.equal((await db.supplierPaymentPlan.findUniqueOrThrow({where:{id:plan.id}})).plannedAmount.toString(),'100');
});
