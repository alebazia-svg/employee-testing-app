import test from 'node:test';
import assert from 'node:assert/strict';
import {PrismaClient} from '@prisma/client';
import {mkdtemp,readdir,readFile} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {saveProcurementReceipt,readProcurementReceipt,receiptPlan} from '../lib/procurement-receipts';

const url=process.env.DATABASE_URL||'';
if(url!=='postgresql://postgres@127.0.0.1:55439/procurement_receipts_current_test')throw Error('ISOLATED_RECEIPT_TEST_DATABASE_REQUIRED');
const db=new PrismaClient();
test.after(()=>db.$disconnect());
test('real PostgreSQL: both authors, concurrent retries, durable bytes, permissions, and no financial mutations',async()=>{
  const marker=randomUUID();
  const makeUser=(role:string,area:string)=>db.user.create({data:{name:`Test ${role}`,login:`receipt-${role}-${randomUUID()}`,passwordHash:'NO_LOGIN',role,portalArea:area}});
  const admin=await makeUser('ADMIN','WORKDAY');
  const owner=await makeUser('EMPLOYEE','PROCUREMENT');
  const other=await makeUser('EMPLOYEE','PROCUREMENT');
  const plan=await db.supplierPaymentPlan.create({data:{planCode:marker,managerUserId:owner.id,supplierPartner:'TEST ONLY',orderRefs:[],orderNumbers:[],plannedDate:new Date('2026-10-10'),plannedAmount:100,condition:'TEST',paymentMethod:'BANK',status:'APPROVED',oneCCashEvidence:{testPaid:true},oneCIssuedAmount:100}});
  const root=await mkdtemp(path.join(os.tmpdir(),'procurement-receipts-test-'));
  const bytes=await readFile('public/favicon-32x32.png');
  const file=new File([bytes],'test-receipt.png',{type:'image/png'});
  const concurrent=await Promise.all([saveProcurementReceipt(db,admin,plan.id,file,root),saveProcurementReceipt(db,admin,plan.id,file,root)]);
  assert.equal(concurrent.filter(r=>!r.duplicate).length,1);
  assert.equal(concurrent[0].receipt.id,concurrent[1].receipt.id);
  assert.equal((await readdir(root)).length,1);
  const read=await readProcurementReceipt(db,owner,plan.id,concurrent[0].receipt.id,root);
  assert.deepEqual(read.bytes,bytes);
  await assert.rejects(readProcurementReceipt(db,other,plan.id,read.receipt.id,root),/не найдена/);
  await assert.rejects(saveProcurementReceipt(db,other,plan.id,file,root),/не найдена/);
  await assert.rejects(saveProcurementReceipt(db,owner,plan.id,new File(['html'],'bad.png',{type:'image/png'}),root),/настоящий/);
  assert.equal(await db.workdayNotification.count({where:{userId:owner.id,kind:'procurement_receipt_added'}}),1);
  const buyerFile=new File(['%PDF-1.7\nTEST ONLY\n%%EOF'],'test-receipt.pdf',{type:'application/pdf'});
  const second=await saveProcurementReceipt(db,owner,plan.id,buyerFile,root);
  const event=await db.adminInboxEvent.findUniqueOrThrow({where:{eventKey:`procurement-receipt:${second.receipt.id}`},include:{receipts:true}});
  assert.ok(event.receipts.some(r=>r.userId===admin.id));
  assert.equal(event.receipts.some(r=>r.userId===owner.id),false);
  assert.ok(event.href.includes(`receipts=${plan.id}`));
  assert.deepEqual(await db.supplierPaymentPlan.findUnique({where:{id:plan.id}}),plan);
  await db.user.update({where:{id:owner.id},data:{isActive:false}});
  await assert.rejects(receiptPlan(db,{...owner,isActive:false},plan.id),/не найдена/);
  assert.equal(await db.supplierPaymentPlanEvent.count({where:{planId:plan.id,action:'RECEIPT_ADDED'}}),2);
});
