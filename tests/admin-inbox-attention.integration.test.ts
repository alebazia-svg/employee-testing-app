import assert from 'node:assert/strict';
import test from 'node:test';
import bcrypt from 'bcryptjs';
import webpush from 'web-push';
import { prisma } from '../lib/prisma';
import { loadAdminInbox } from '../lib/admin-inbox-data';
import { dispatchAdminInboxWebPush } from '../lib/admin-inbox-web-push';
import { dispatchAdminAttentionPush } from '../lib/admin-inbox-attention-push';

// A dedicated disposable database only; no network push is ever sent by this test.
const enabled = process.env.ATTENTION_INTEGRATION === '1';
test('real database: noise, read/resolve/reopen, batch plans, multiple devices, retries, leases and reminders', { skip: !enabled }, async () => {
  assert.ok(process.env.DATABASE_URL?.endsWith('@127.0.0.1:55448/admin_attention_20261012_test'));
  const originalSend = webpush.sendNotification;
  const originalConfigure = webpush.setVapidDetails;
  const savedKeys = [process.env.WEB_PUSH_VAPID_PUBLIC_KEY, process.env.WEB_PUSH_VAPID_PRIVATE_KEY];
  process.env.WEB_PUSH_VAPID_PUBLIC_KEY = 'isolated-test';
  process.env.WEB_PUSH_VAPID_PRIVATE_KEY = 'isolated-test';
  webpush.setVapidDetails = () => undefined;
  const prefix = `attention-test-${Date.now()}`;
  let failEndpoint = '';
  const sent: { endpoint: string; payload: any }[] = [];
  webpush.sendNotification = async (sub, payload) => {
    if (sub.endpoint === failEndpoint) throw Object.assign(new Error('simulated transient failure'), {statusCode:503});
    sent.push({endpoint:sub.endpoint,payload:JSON.parse(String(payload))});
    return {statusCode:201,body:'',headers:{}};
  };
  const now = new Date('2026-10-12T09:00:00Z');
  try {
    const admin = await prisma.user.create({data:{name:'Проверка уведомлений',login:prefix,passwordHash:await bcrypt.hash('isolated-notification-demo',4),role:'ADMIN'}});
    const manager = await prisma.user.create({data:{name:'Менеджер · тест',login:`${prefix}-manager`,passwordHash:'unused',role:'EMPLOYEE'}});
    const event = async (key:string,type:string,sourceType:string,sourceId:string,read=false,occurredAt=new Date('2026-10-01T09:00:00Z')) => prisma.adminInboxEvent.create({data:{eventKey:key,type,sourceType,sourceId,title:type,body:'Учебное событие',href:'/admin/expense-requests',occurredAt,receipts:{create:{userId:admin.id,readAt:read?now:null}}}});
    const ref = `${prefix}-expense`;
    const c = await prisma.expenseRequestAdminCase.create({data:{oneCRequestRef:ref,isNotApproved:true,currentCycleOrigin:'live',notApprovedCycle:2,deletionMark:false}});
    await event(`expense_request:not_approved:${ref}:1`,'expense_request.created','expense_request',ref);
    const current = await event(`expense_request:not_approved:${ref}:2`,'expense_request.created','expense_request',ref,true);
    for(let n=0;n<210;n++) await event(`${prefix}:noise:${n}`,'infrastructure.down','infrastructure',`${prefix}-connection`,false,now);
    const planBase = {managerUserId:manager.id,supplierPartner:'Учебный поставщик',orderRefs:[],orderNumbers:[],plannedDate:now,plannedAmount:1000,condition:'',paymentMethod:'CASH'};
    const plan1 = await prisma.supplierPaymentPlan.create({data:{...planBase,planCode:`${prefix}-1`}});
    const plan2 = await prisma.supplierPaymentPlan.create({data:{...planBase,planCode:`${prefix}-2`}});
    await event(`${prefix}:batch`,'procurement.payment_submitted','supplier_payment_plan',plan1.id);
    const delivery = await event(`${prefix}:delivery`, 'procurement.delivery_requested', 'procurement_delivery', `${prefix}-person`);
    await event(`delivery:manual:${delivery.id}`, 'procurement.delivery_manual_requested', 'procurement_delivery_request', `${prefix}-person`);
    let withDelivery = await loadAdminInbox({userId:admin.id,limit:8,view:'attention'});
    assert.equal(withDelivery.attention.filter(i=>i.event.sourceId===`${prefix}-person`).length,1,'manual and reserve request form one task');
    await event(`${prefix}:covered`, 'procurement.delivery_covered', 'procurement_delivery', `${prefix}-person`);
    withDelivery = await loadAdminInbox({userId:admin.id,limit:8,view:'attention'});
    assert.equal(withDelivery.attention.filter(i=>i.event.sourceId===`${prefix}-person`).length,0,'closure also retires old manual marker');
    let inbox = await loadAdminInbox({userId:admin.id,limit:8,view:'attention'});
    assert.equal(inbox.attentionCount,3);
    assert.equal(inbox.items[0].eventId,current.id);
    assert.equal(inbox.technicalCount,1);
    assert.ok((await loadAdminInbox({userId:admin.id,limit:8,view:'history'})).items.some(i=>i.event.type==='expense_request.created'),'technical traffic cannot crowd out business history');
    assert.equal((await loadAdminInbox({userId:admin.id,limit:200,view:'system'})).items.filter(i=>i.sourceState.active).length,1,'system has only one active outage per source');
    assert.ok(inbox.attention.some(i=>i.event.sourceId===plan2.id));
    await prisma.supplierPaymentPlan.update({where:{id:plan1.id},data:{status:'APPROVED'}});
    await prisma.adminInboxReceipt.updateMany({where:{userId:admin.id},data:{readAt:now}});
    inbox = await loadAdminInbox({userId:admin.id,limit:8,view:'attention'});
    assert.equal(inbox.attentionCount,2,'read-all and approval of first batch plan cannot hide second');
    const a = await prisma.workdayPushSubscription.create({data:{userId:admin.id,endpoint:`https://test.invalid/${prefix}/a`,p256dh:'test',auth:'test',userAgent:'test'}});
    const b = await prisma.workdayPushSubscription.create({data:{userId:admin.id,endpoint:`https://test.invalid/${prefix}/b`,p256dh:'test',auth:'test',userAgent:'test'}});
    let result = await dispatchAdminInboxWebPush(now);
    assert.equal(result.sent,2,'old pending events reach both newly registered devices');
    assert.equal(sent.length,2); assert.equal(sent[0].payload.badgeCount,2);
    const notificationId = sent[0].payload.notificationId;
    await dispatchAdminAttentionPush(new Date(+now+14*60000)); assert.equal(sent.length,2);
    await dispatchAdminAttentionPush(new Date(+now+15*60000)); assert.equal(sent.length,4);
    await dispatchAdminAttentionPush(new Date(+now+74*60000)); assert.equal(sent.length,4);
    failEndpoint = b.endpoint;
    result = await dispatchAdminAttentionPush(new Date(+now+75*60000)); assert.equal(result.sent,1); assert.equal(result.failed,1);
    await dispatchAdminAttentionPush(new Date(+now+79*60000)); assert.equal(sent.length,5);
    failEndpoint = '';
    await dispatchAdminAttentionPush(new Date(+now+80*60000)); assert.equal(sent.length,6);
    assert.ok(sent.every(s=>s.payload.notificationId===notificationId),'repeats update one OS summary');
    const digest = await prisma.adminInboxEvent.findUniqueOrThrow({where:{eventKey:`admin:attention-digest:v1:${admin.id}`}});
    assert.equal(await prisma.adminInboxReceipt.count({where:{eventId:digest.id}}),0,'no repeated bell entries');
    assert.equal(await prisma.adminInboxDelivery.count({where:{eventId:digest.id}}),2,'one durable row per device');
    await prisma.adminInboxDelivery.updateMany({where:{eventId:digest.id},data:{status:'sending',leaseToken:'interrupted',leaseUntil:new Date(+now+145*60000)}});
    await dispatchAdminAttentionPush(new Date(+now+144*60000)); assert.equal(sent.length,6);
    await Promise.all([dispatchAdminAttentionPush(new Date(+now+145*60000)),dispatchAdminAttentionPush(new Date(+now+145*60000))]);
    assert.equal(sent.length,8,'expired lease recovers once per device under concurrent dispatch');
    await prisma.expenseRequestAdminCase.update({where:{id:c.id},data:{isNotApproved:false,currentStatusKey:'payable'}});
    await prisma.supplierPaymentPlan.update({where:{id:plan2.id},data:{status:'APPROVED'}});
    assert.equal((await loadAdminInbox({userId:admin.id,limit:8,view:'attention'})).attentionCount,0);
    await dispatchAdminAttentionPush(new Date(+now+205*60000)); assert.equal(sent.length,8,'resolved items stop reminders');
    await prisma.expenseRequestAdminCase.update({where:{id:c.id},data:{isNotApproved:true,notApprovedCycle:3}});
    await event(`expense_request:not_approved:${ref}:3`,'expense_request.created','expense_request',ref);
    assert.equal((await loadAdminInbox({userId:admin.id,limit:8,view:'attention'})).attentionCount,1,'new cycle reopens exactly one item');
    await prisma.supplierPaymentPlan.update({where:{id:plan2.id},data:{oneCCashEvidence:{pendingRevision:{id:'test-revision',submittedAt:now.toISOString(),data:{plannedAmount:2000},changes:[]}}}});
    assert.ok((await loadAdminInbox({userId:admin.id,limit:8,view:'attention'})).attention.some(i=>i.id.includes('test-revision')),'approved plan with proposed changes returns to owner queue');
    const late = new Date('2026-10-12T19:30:00Z');
    const closing = await event(`${prefix}:closing`, 'workday.close_exception_requested', 'workday_close_exception', `${prefix}-close`, false, late);
    await prisma.adminInboxEvent.update({where:{id:closing.id},data:{createdAt:late}});
    const beforeClosing=sent.length;
    assert.equal((await dispatchAdminInboxWebPush(late)).sent,2,'22–23 closing blockers retain their separate channel');
    assert.equal(sent.length,beforeClosing+2);
    await prisma.expenseRequestAdminCase.delete({where:{id:c.id}});
    await prisma.adminInboxEvent.deleteMany({where:{OR:[{eventKey:{contains:prefix}},{eventKey:`delivery:manual:${delivery.id}`},{id:digest.id}]}});
    await prisma.supplierPaymentPlan.deleteMany({where:{managerUserId:manager.id}});
    await prisma.user.deleteMany({where:{id:{in:[admin.id,manager.id]}}});
  } finally { webpush.sendNotification=originalSend; webpush.setVapidDetails=originalConfigure;
    for (const [i,key] of ['WEB_PUSH_VAPID_PUBLIC_KEY','WEB_PUSH_VAPID_PRIVATE_KEY'].entries()) { if(savedKeys[i]===undefined) delete process.env[key]; else process.env[key]=savedKeys[i]; }
    await prisma.$disconnect(); }
});
